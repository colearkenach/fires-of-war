function cleanTrait(value) {
    return typeof value === "string" ? value.trim() : "";
}

/** Normalize a class node's three base/optional trait pairs. */
export function normalizeClassRoleplayTraits(value) {
    if (!Array.isArray(value)) return [];
    return value.slice(0, 3).map(entry => {
        if (Array.isArray(entry)) return { base: cleanTrait(entry[0]), alternative: cleanTrait(entry[1]) };
        return { base: cleanTrait(entry?.base ?? entry?.name), alternative: cleanTrait(entry?.alternative ?? entry?.optional) };
    }).filter(entry => entry.base || entry.alternative);
}

/** Prefer explicit class-item data, falling back to the published class table. */
export function getClassRoleplayTraits(className, configured) {
    const explicit = normalizeClassRoleplayTraits(configured);
    if (explicit.length) return explicit;
    return normalizeClassRoleplayTraits(CLASS_ROLEPLAY_TRAITS[cleanTrait(className)]);
}

export function roleplayTraitFormula(hasRelevantTrait) {
    return hasRelevantTrait ? "2d10kh1" : "1d10";
}

export function clampTraitTarget(value) {
    const number = Number(value);
    if (!Number.isFinite(number)) return 6;
    return Math.min(Math.max(Math.floor(number), 2), 10);
}

export function isSuccessfulTraitRoll(total, target) {
    return Number(total) >= clampTraitTarget(target);
}

